                    height: 1.5,
                    color: Color(0xFFE2E8F0),
                  ),
                ),
              ],
            ),
          ),
      ],
    );
  }

  Widget _aiDisclaimerBanner() {
    return Container(
      padding: const EdgeInsets.symmetric(horizontal: 10, vertical: 6),
      decoration: BoxDecoration(
        color: const Color(0xFF14B8A6).withOpacity(0.12),
        borderRadius: BorderRadius.circular(8),
        border: Border.all(
          color: const Color(0xFF14B8A6).withOpacity(0.35),
        ),
      ),
      child: const Row(
        children: [
          Icon(Icons.auto_awesome_rounded, size: 13, color: Color(0xFF2DD4BF)),
          SizedBox(width: 6),
          Expanded(
            child: Text(
              'Generated by AI · Temporary session',
              style: TextStyle(
                fontFamily: 'Inter',
                fontSize: 11,
                fontWeight: FontWeight.w600,
                color: Color(0xFF2DD4BF),
              ),
            ),
          ),
        ],
      ),
    );
  }

  String _breadcrumb() {
    final parts = [
      if (widget.subjectName != null) widget.subjectName!,
      if (widget.topicName != null && widget.topicName != widget.node.label)
        widget.topicName!,
      widget.node.label,
    ];
    return parts.join('  ›  ');
  }

  Widget _nodeTypeBadge(GraphNodeType type) {
    final (label, color) = switch (type) {
      GraphNodeType.subject => ('SUBJECT', const Color(0xFF3B82F6)),
      GraphNodeType.topic => ('TOPIC', const Color(0xFF2F6FDD)),
      GraphNodeType.subtopic => ('SUBTOPIC', const Color(0xFF38BDF8)),
      GraphNodeType.aiExpanded => ('AI EXPANSION', const Color(0xFF2DD4BF)),
    };

    return Container(
      padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 3),
      decoration: BoxDecoration(
        color: color.withOpacity(0.15),
        borderRadius: BorderRadius.circular(6),
        border: Border.all(color: color.withOpacity(0.40)),
      ),
      child: Text(
        label,
        style: TextStyle(
          fontFamily: 'Inter',
          fontSize: 9.5,
          fontWeight: FontWeight.w700,
          color: color,
          letterSpacing: 0.5,
        ),
      ),
    );
  }
}

