/// NotebookLM-style side panel shown when any node is clicked.
/// Built with the application's navy/blue theme (#102743 panel background).
/// Displays:
/// - Title & Hierarchy breadcrumbs
/// - Student Notes from Firestore
/// - AI-enhanced explanations, Key Concepts, Examples, Quick Revision
/// - Action shortcuts: Quiz, Flashcards, AI Expand
/// - "Generated by AI · Temporary" banner
class GraphDetailPanel extends ConsumerStatefulWidget {
  final GraphNode node;
  final GraphAiService aiService;
  final VoidCallback onClose;
  final String? subjectName;
  final String? topicName;
  final VoidCallback? onAiExpand;
  final void Function(String route, String nodeId)? onNavigateTool;

  const GraphDetailPanel({
    required this.node,
    required this.aiService,
    required this.onClose,
    super.key,
    this.subjectName,
    this.topicName,
    this.onAiExpand,
    this.onNavigateTool,
  });

  @override
  ConsumerState<GraphDetailPanel> createState() => _GraphDetailPanelState();
}

class _GraphDetailPanelState extends ConsumerState<GraphDetailPanel> {
  NodeExplanation? _explanation;
  bool _loading = false;
  String? _error;
  int _selectedTab = 0;
  int _explanationRequestId = 0;

  // Tabs tailored to study workflow
  static const _tabs = [
    'Notes',
    'AI Explanation',
    'Key Concepts',
    'Examples',
    'Quick Revision',
  ];

  static const Color _panelBg = Color(0xFF102743);
  static const Color _panelBorder = Color(0xFF1E3A5F);

  @override
  void initState() {
    super.initState();
    // Default to 'Notes' if node has notes, else 'AI Explanation'
    _selectedTab = widget.node.notes.isNotEmpty ? 0 : 1;
    _loadExplanation();
  }

  @override
  void didUpdateWidget(GraphDetailPanel old) {
    super.didUpdateWidget(old);
    if (old.node.id != widget.node.id ||
        old.node.label != widget.node.label ||
        old.node.notes.toString() != widget.node.notes.toString() ||
        old.subjectName != widget.subjectName ||
        old.topicName != widget.topicName) {
      _explanation = null;
      _selectedTab = widget.node.notes.isNotEmpty ? 0 : 1;
      _loadExplanation();
    }
  }

  Future<void> _loadExplanation() async {
    final requestId = ++_explanationRequestId;
    setState(() {
      _loading = true;
      _error = null;
    });

    try {
      // Pass student's actual Firestore notes if present
      final notesText = widget.node.notes.isNotEmpty
          ? widget.node.notes
              .map((n) => '${n['title'] ?? 'Note'}: ${n['content'] ?? ''}')
              .join('\n\n')
          : null;
      var summary = widget.node.description;
      if ((notesText == null || notesText.trim().isEmpty) &&
          (summary == null || summary.trim().isEmpty)) {
        final subjectId = widget.node.subjectId ??
            (widget.node.type == GraphNodeType.subject ? widget.node.id : null);
        if (subjectId != null && subjectId.isNotEmpty) {
          summary = await ref
              .read(knowledgeEngineProvider)
              .getCachedStudySummary(subjectId);
        }
      }
      if (!mounted || requestId != _explanationRequestId) return;

      final explanation = await widget.aiService.explainNode(
        nodeLabel: widget.node.label,
        nodeType: widget.node.type,
        notes: notesText,
        summary: summary,
        subjectName: widget.subjectName,
        topicName: widget.topicName,
      );
      if (mounted && requestId == _explanationRequestId) {
        setState(() => _explanation = explanation);
      }
    } catch (e) {
      if (mounted && requestId == _explanationRequestId) {
        setState(() => _error = e.toString());
      }
    } finally {
      if (mounted && requestId == _explanationRequestId) {
        setState(() => _loading = false);
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    final isDesktop = MediaQuery.of(context).size.width > 900;
    if (isDesktop) {
      return _buildDesktopPanel();
    }
    return _buildMobileSheet();
  }

  Widget _buildDesktopPanel() {
    return Container(
      width: 400,
      height: double.infinity,
      decoration: const BoxDecoration(
        color: _panelBg,
        border: Border(
          left: BorderSide(color: _panelBorder, width: 1.2),
        ),
        boxShadow: [
          BoxShadow(
            color: Color(0x33000000),
            blurRadius: 20,
            offset: Offset(-4, 0),
          ),
        ],
      ),
      child: _panelContent(),
    );
  }

  Widget _buildMobileSheet() {
    return Container(
      constraints: BoxConstraints(
        maxHeight: MediaQuery.of(context).size.height * 0.78,
      ),
      decoration: BoxDecoration(
        color: _panelBg,
        borderRadius: const BorderRadius.vertical(top: Radius.circular(24)),
        border: Border.all(color: _panelBorder, width: 1.2),
        boxShadow: const [
          BoxShadow(
            color: Color(0x40000000),
            blurRadius: 24,
            offset: Offset(0, -6),
          ),
        ],
      ),
      child: _panelContent(),
    );
  }

  Widget _panelContent() {
    final node = widget.node;
    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        // ── Header: Node Badge, Title, Hierarchy, Close ───────────────────────
        Container(
          padding: const EdgeInsets.fromLTRB(18, 16, 12, 14),
          decoration: const BoxDecoration(
            border: Border(bottom: BorderSide(color: _panelBorder)),
          ),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Row(
                children: [
                  _nodeTypeBadge(node.type),
                  const Spacer(),
                  IconButton(
                    onPressed: widget.onClose,
                    icon: const Icon(
                      Icons.close_rounded,
                      color: Color(0xFF94A3B8),
                      size: 20,
                    ),
                    style: IconButton.styleFrom(
                      minimumSize: const Size(32, 32),
                      padding: EdgeInsets.zero,
                    ),
                    tooltip: 'Close panel',
                  ),
                ],
              ),
              const SizedBox(height: 8),
              Text(
                node.label,
                style: const TextStyle(
                  fontFamily: 'Inter',
                  fontSize: 18,
                  fontWeight: FontWeight.w700,
                  letterSpacing: -0.4,
                  color: Colors.white,
                ),
              ),
              // Hierarchy Breadcrumb
              Padding(
                padding: const EdgeInsets.only(top: 4),
                child: Row(
                  children: [
                    const Icon(Icons.account_tree_outlined,
                        size: 13, color: Color(0xFF64748B)),
                    const SizedBox(width: 6),
                    Expanded(
                      child: Text(
                        _breadcrumb(),
                        overflow: TextOverflow.ellipsis,
                        style: const TextStyle(
                          fontFamily: 'Inter',
                          fontSize: 11.5,
                          color: Color(0xFF94A3B8),
                        ),
                      ),
                    ),
                  ],
                ),
              ),
            ],
          ),
        ),

        // ── Action Buttons ───────────────────────────────────────────────────
        Padding(
          padding: const EdgeInsets.fromLTRB(14, 12, 14, 0),
          child: _quickActions(),
        ),

        // ── Tab Bar ───────────────────────────────────────────────────────────
        Container(
          margin: const EdgeInsets.fromLTRB(14, 12, 14, 0),
          height: 34,
          child: ListView.separated(
            scrollDirection: Axis.horizontal,
            itemCount: _tabs.length,
            separatorBuilder: (_, __) => const SizedBox(width: 6),
            itemBuilder: (context, i) => _tabChip(i),
          ),
        ),

        // ── Content Area ───────────────────────────────────────────────────────
        Expanded(
          child: SingleChildScrollView(
            padding: const EdgeInsets.all(16),
            child: _tabContent(),
          ),
        ),
      ],
    );
  }

  Widget _quickActions() {
    final node = widget.node;
    final nodeId = node.type == GraphNodeType.subject
        ? 'current'
        : node.topicId ?? node.id;
    final actions = [
      _ActionBtn(
        icon: Icons.style_rounded,
        label: 'Generate Flashcards',
        color: const Color(0xFF38BDF8),
        onTap: () => widget.onNavigateTool?.call('flashcards', nodeId),
      ),
      _ActionBtn(
        icon: Icons.quiz_rounded,
        label: 'Generate Quiz',
        color: const Color(0xFF34D399),
        onTap: () => widget.onNavigateTool?.call('quiz', nodeId),
      ),
      _ActionBtn(
        icon: Icons.assignment_rounded,
        label: 'Generate PYQs',
        color: const Color(0xFFFBBF24),
        onTap: () => widget.onNavigateTool?.call('pyq', nodeId),
      ),
      _ActionBtn(
        icon: Icons.account_tree_rounded,
        label: 'Expand Further',
        color: const Color(0xFF2DD4BF),
        onTap: widget.onAiExpand,
      ),
      _ActionBtn(
        icon: Icons.copy_rounded,
        label: 'Copy Notes',
        color: const Color(0xFFA78BFA),
        onTap: _copyNotes,
      ),
      _ActionBtn(
        icon: Icons.refresh_rounded,
        label: 'Refresh AI Explanation',
        color: const Color(0xFFFB7185),
        onTap: _loading ? null : _loadExplanation,
      ),
    ];

    return LayoutBuilder(
      builder: (context, constraints) {
        final itemWidth = (constraints.maxWidth - 12) / 3;
        return Wrap(
          spacing: 6,
          runSpacing: 6,
          children: [
            for (final action in actions)
              SizedBox(width: itemWidth, child: action),
          ],
        );
      },
    );
  }

  Future<void> _copyNotes() async {
    final notes = widget.node.notes
        .map((note) =>
            '${note['title'] ?? 'Note'}: ${note['content'] ?? note['notes'] ?? ''}')
        .where((note) => note.trim().isNotEmpty)
        .join('\n\n');
    final content = notes.isNotEmpty
        ? notes
        : _explanation?.detailedExplanation ?? _explanation?.overview ?? '';
    if (content.trim().isEmpty) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          const SnackBar(content: Text('No notes or explanation to copy yet.')),
        );
      }
      return;
    }
    await Clipboard.setData(ClipboardData(text: content));
    if (mounted) {
      ScaffoldMessenger.of(context).showSnackBar(
        const SnackBar(content: Text('Notes copied')),
      );
    }
  }

  Widget _tabChip(int index) {
    final selected = _selectedTab == index;
    final hasBadge = index == 0 && widget.node.notes.isNotEmpty;

    return GestureDetector(
      onTap: () => setState(() => _selectedTab = index),
      child: AnimatedContainer(
        duration: const Duration(milliseconds: 180),
        padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 6),
        decoration: BoxDecoration(
          color: selected
              ? const Color(0xFF2563EB)
              : const Color(0xFF1E3A5F).withOpacity(0.45),
          borderRadius: BorderRadius.circular(20),
          border: Border.all(
            color: selected ? const Color(0xFF3B82F6) : const Color(0xFF1E3A5F),
          ),
        ),
        child: Row(
          mainAxisSize: MainAxisSize.min,
          children: [
            Text(
              _tabs[index],
              style: TextStyle(
                fontFamily: 'Inter',
                fontSize: 11.5,
                fontWeight: selected ? FontWeight.w700 : FontWeight.w500,
                color: selected ? Colors.white : const Color(0xFFCBD5E1),
              ),
            ),
            if (hasBadge) ...[
              const SizedBox(width: 5),
              Container(
                padding: const EdgeInsets.symmetric(horizontal: 5, vertical: 1),
                decoration: BoxDecoration(
                  color: const Color(0xFF0284C7),
                  borderRadius: BorderRadius.circular(10),
                ),
                child: Text(
                  '${widget.node.notes.length}',
                  style: const TextStyle(
                    fontFamily: 'Inter',
                    fontSize: 9.5,
                    fontWeight: FontWeight.w700,
                    color: Colors.white,
                  ),
                ),
              ),
            ],
          ],
        ),
      ),
    );
  }

  Widget _tabContent() {
    // Tab 0: Student Notes
    if (_selectedTab == 0) {
      return _buildStudentNotesSection();
    }

    // For AI tabs: check loading/error
    if (_loading) {
      return const _AiLoadingView();
    }
    if (_error != null) {
      return _AiErrorView(error: _error!, onRetry: _loadExplanation);
    }
    if (_explanation == null) {
      return const Center(
          child: Text('No explanation available.',
              style: TextStyle(color: Colors.white70)));
    }

    final exp = _explanation!;

    return switch (_selectedTab) {
      1 => Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            _aiDisclaimerBanner(),
            const SizedBox(height: 12),
            _SectionBox(
              title: 'Overview',
              icon: Icons.info_outline_rounded,
              content: exp.overview.isNotEmpty
                  ? exp.overview
                  : 'No overview available.',
            ),
            const SizedBox(height: 12),
            _SectionBox(
              title: 'Detailed Explanation',
              icon: Icons.menu_book_rounded,
              content: exp.detailedExplanation.isNotEmpty
                  ? exp.detailedExplanation
                  : 'No detailed explanation available.',
            ),
            if (exp.whyMatters.isNotEmpty) ...[
              const SizedBox(height: 12),
              _SectionBox(
                title: 'Why This Topic Matters',
                icon: Icons.flag_outlined,
                content: exp.whyMatters,
              ),
            ],
            if (exp.relatedConcepts.isNotEmpty) ...[
              const SizedBox(height: 12),
              _SectionBox(
                title: 'Related Concepts',
                icon: Icons.hub_outlined,
                content: exp.relatedConcepts,
              ),
            ],
          ],
        ),
      2 => Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            _aiDisclaimerBanner(),
            const SizedBox(height: 12),
            _SectionBox(
              title: 'Key Concepts',
              icon: Icons.lightbulb_outline_rounded,
              content: exp.keyConcepts.isNotEmpty
                  ? exp.keyConcepts
                  : 'No key concepts available.',
            ),
            if (exp.formulas.isNotEmpty) ...[
              const SizedBox(height: 12),
              _SectionBox(
                title: 'Key Formulas & Rules',
                icon: Icons.functions_rounded,
                content: exp.formulas,
                isCode: true,
              ),
            ],
          ],
        ),
      3 => Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            _aiDisclaimerBanner(),
            const SizedBox(height: 12),
            _SectionBox(
              title: 'Practical Examples',
              icon: Icons.psychology_alt_outlined,
              content: exp.examples.isNotEmpty
                  ? exp.examples
                  : 'No examples generated yet.',
            ),
            if (exp.realWorldExample.isNotEmpty) ...[
              const SizedBox(height: 12),
              _SectionBox(
                title: 'Real-world Example',
                icon: Icons.public_rounded,
                content: exp.realWorldExample,
              ),
            ],
          ],
        ),
      4 => Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            _aiDisclaimerBanner(),
            const SizedBox(height: 12),
            _SectionBox(
              title: 'Summary',
              icon: Icons.summarize_outlined,
              content: exp.summary.isNotEmpty
                  ? exp.summary
                  : 'No summary available.',
            ),
            if (exp.memoryTricks.isNotEmpty) ...[
              const SizedBox(height: 12),
              _SectionBox(
                title: 'Memory Mnemonics',
                icon: Icons.tips_and_updates_outlined,
                content: exp.memoryTricks,
              ),
            ],
            if (exp.examQuestions.isNotEmpty) ...[
              const SizedBox(height: 12),
              _SectionBox(
                title: 'Likely Exam Questions',
                icon: Icons.assignment_outlined,
                content: exp.examQuestions,
              ),
            ],
            if (exp.interviewQuestions.isNotEmpty) ...[
              const SizedBox(height: 12),
              _SectionBox(
                title: 'Common Questions',
                icon: Icons.question_answer_outlined,
                content: exp.interviewQuestions,
              ),
            ],
          ],
        ),
      _ => const SizedBox.shrink(),
    };
  }

  Widget _buildStudentNotesSection() {
    final notes = widget.node.notes;
    if (notes.isEmpty) {
      return Center(
        child: Padding(
          padding: const EdgeInsets.symmetric(vertical: 36),
          child: Column(
            mainAxisSize: MainAxisSize.min,
            children: [
              Container(
                padding: const EdgeInsets.all(16),
                decoration: const BoxDecoration(
                  color: Color(0xFF1E3A5F),
                  shape: BoxShape.circle,
                ),
                child: const Icon(
                  Icons.sticky_note_2_outlined,
                  size: 32,
                  color: Color(0xFF38BDF8),
                ),
              ),
              const SizedBox(height: 14),
              const Text(
                'No Notes for This Concept',
