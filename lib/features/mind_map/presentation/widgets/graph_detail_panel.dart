              height: 16,
              child: CircularProgressIndicator(
                strokeWidth: 2,
                color: Color(0xFF2DD4BF),
              ),
            ),
            SizedBox(width: 10),
            Text(
              'Gemini AI is analyzing topic and notes…',
              style: TextStyle(
                fontFamily: 'Inter',
                fontSize: 12,
                color: Color(0xFF2DD4BF),
              ),
            ),
          ],
